# LAMBDA HANDLER — entry point
# ══════════════════════════════════════════════════════════════════════════════


def lambda_handler(event: dict, context: Any) -> dict:
    """
    Lambda entry point. Invoked automatically every Tuesday via EventBridge.

    Iterates over all channels in CHANNELS, runs the viewer report and/or
    event creation tasks based on the mode, then sends a summary email.

    The event payload controls what runs:
        {}                              Run both tasks for all channels + send email.
        {"mode": "viewer_report"}       Only fetch viewer counts and send email.
        {"mode": "create_events"}       Only create next Sunday's events.
        {"channel": "ms_channel"}       Run both tasks for one channel only.
        {"dry_run": true}               Full run with no YouTube writes or email.

    Always returns HTTP 200 with a JSON body containing a summary and the
    per-channel results for both tasks. Errors on individual channels are
    captured in the results and do not cause a non-200 response.
    """
    mode = event.get("mode", "both")  # "both" | "viewer_report" | "create_events"
    target_channel = event.get("channel")  # optional single-channel filter
    dry_run = event.get("dry_run", False)

    last_sunday = get_last_sunday()
    next_sunday = get_next_sunday()

    logger.info(
        "Lambda invoked | mode=%s | channel=%s | dry_run=%s | last_sunday=%s | next_sunday=%s",
        mode,
        target_channel or "all",
        dry_run,
        last_sunday,
        next_sunday,
    )

    viewer_results = []
    event_results = []

    for channel_key, channel in CHANNELS.items():
        if target_channel and channel_key != target_channel:
            continue

        if mode in ("both", "viewer_report"):
            viewer_results.append(fetch_viewer_stats(channel_key, channel, last_sunday))

        if mode in ("both", "create_events") and channel.get("create_events", True):
            event_results.append(
                schedule_next_event(channel_key, channel, next_sunday, dry_run)
            )

    # Sync viewer counts to the Google Sheet's Raw Log (skip during dry_run)
    sheet_sync_result = None
    if mode in ("both", "viewer_report") and not dry_run:
        sheet_sync_result = send_to_sheet(viewer_results, last_sunday)

    # Send combined email (skip for single-channel runs or dry_run)
    email_sent = False
    if not target_channel and not dry_run and mode in ("both", "viewer_report"):
        subject, html_body = build_email(
            viewer_results, event_results, last_sunday, next_sunday
        )
        email_sent = send_email(subject, html_body)

    v_ok = sum(1 for r in viewer_results if r["status"] == "success")
    v_err = sum(1 for r in viewer_results if r["status"] == "error")
    e_ok = sum(1 for r in event_results if r["status"] in ("created", "dry_run"))
    e_err = sum(1 for r in event_results if r["status"] == "error")

    summary = {
        "last_sunday": str(last_sunday),
        "next_sunday": str(next_sunday),
        "email_sent": email_sent,
        "sheet_sync": sheet_sync_result,
        "viewer_report": {"success": v_ok, "errors": v_err},
        "event_creation": {"success": e_ok, "errors": e_err},
    }

    logger.info("Done: %s", summary)
    return {
        "statusCode": 200,
        "body": json.dumps(
            {
                "summary": summary,
                "viewer_results": viewer_results,
                "event_results": event_results,
            }
        ),
    }
