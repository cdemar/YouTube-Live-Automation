# AUTH
# ══════════════════════════════════════════════════════════════════════════════
# Handles Google OAuth2 authentication. Each channel's refresh token is stored
# in a Lambda environment variable and exchanged for a short-lived access token
# at runtime. The access token is never stored — it exists only for the duration
# of the Lambda invocation.
#
# IMPORTANT: Refresh tokens must be generated with BOTH scopes:
#   - https://www.googleapis.com/auth/youtube           (create/manage events)
#   - https://www.googleapis.com/auth/yt-analytics.readonly  (viewer counts)
# The consent screen must show "Manage your YouTube account" AND
# "View YouTube Analytics reports" when you run get_refresh_token.py.


def get_youtube_client(refresh_token: str) -> tuple:
    """
    Build authenticated YouTube Data AND YouTube Analytics API clients.
    Returns (youtube, youtube_analytics) tuple.

    The Analytics client is used as a reliable fallback for viewer counts
    on streams that ended days ago — the Videos API clears concurrentViewers
    within a few hours of a stream ending, but the Analytics API stores
    peakConcurrentViewers permanently.

    Called once per channel per invocation. Uses GOOGLE_CLIENT_ID and
    GOOGLE_CLIENT_SECRET from Lambda environment variables.
    """
    creds = Credentials(
        token=None,
        refresh_token=refresh_token,
        client_id=os.environ["GOOGLE_CLIENT_ID"],
        client_secret=os.environ["GOOGLE_CLIENT_SECRET"],
        token_uri="https://oauth2.googleapis.com/token",
        scopes=[
            "https://www.googleapis.com/auth/youtube",
            "https://www.googleapis.com/auth/yt-analytics.readonly",
        ],
    )
    creds.refresh(Request())
    youtube = build("youtube", "v3", credentials=creds, cache_discovery=False)
    youtube_analytics = build(
        "youtubeAnalytics", "v2", credentials=creds, cache_discovery=False
    )
    return youtube, youtube_analytics


def get_refresh_token(channel: dict) -> str | None:
    """
    Read a channel's OAuth2 refresh token from Lambda environment variables.

    Returns None and logs an error if the variable is missing, which causes
    the calling function to skip that channel gracefully rather than crash.
    """
    token = os.environ.get(channel["refresh_token_env"])
    if not token:
        logger.error("Missing env var: %s", channel["refresh_token_env"])
    return token


