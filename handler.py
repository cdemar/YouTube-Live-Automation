def send_email(subject: str, html_body: str) -> bool:
    """
    Send the weekly report email via Amazon SES.

    Uses SES_FROM_EMAIL, SES_TO_EMAIL, and SES_REGION from Lambda env vars.
    SES_FROM_EMAIL must be a verified sender identity in your AWS SES account.

    Returns True if the email was accepted by SES, False on failure.
    Email failures are logged but do not cause the Lambda to return an error —
    the YouTube tasks are unaffected regardless of email status.
    """
    ses = boto3.client("ses", region_name=os.environ.get("SES_REGION", "us-west-2"))
    try:
        ses.send_email(
            Source=os.environ["SES_FROM_EMAIL"],
            Destination={"ToAddresses": [os.environ["SES_TO_EMAIL"]]},
            Message={
                "Subject": {"Data": subject, "Charset": "UTF-8"},
                "Body": {"Html": {"Data": html_body, "Charset": "UTF-8"}},
            },
        )
        logger.info("Email sent to %s", os.environ["SES_TO_EMAIL"])
        return True
    except ClientError as e:
        logger.error("SES send failed: %s", e.response["Error"]["Message"])
        return False


