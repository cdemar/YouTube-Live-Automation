# into the Raw Log tab via the same logAttendance() function the attendance
# form uses. Requires SHEET_WEBAPP_URL and SHEET_WEBAPP_SECRET env vars —
# the secret must match WEBAPP_SHARED_SECRET in lambda_integration.gs exactly.


def send_to_sheet(viewer_results: list, last_sunday: datetime.date) -> dict:
    """
    Sends successful viewer counts to the Sheet's Web App endpoint.

    Only sends channels where the viewer report actually succeeded — a
    failed/error channel just doesn't get sent, rather than sending a
    zero or null that could look like a real reported value.

    Non-fatal by design, same as send_email: a Sheet-side hiccup here
    should never block or fail the YouTube automation itself.
    """
    webapp_url = os.environ.get("SHEET_WEBAPP_URL")
    webapp_secret = os.environ.get("SHEET_WEBAPP_SECRET")

    if not webapp_url or not webapp_secret:
        logger.warning("SHEET_WEBAPP_URL or SHEET_WEBAPP_SECRET not configured — skipping sheet sync")
        return {"status": "skipped", "reason": "not configured"}

    results_to_send = []
    for r in viewer_results:
        if r.get("status") == "success" and r.get("max_concurrent_viewers") is not None:
            results_to_send.append({
                "channel": r["channel"],
                "date": str(last_sunday),
                "viewers": r["max_concurrent_viewers"],
            })

    if not results_to_send:
        logger.info("No successful viewer results to send to sheet")
        return {"status": "skipped", "reason": "no successful results"}

    payload = json.dumps({
        "secret": webapp_secret,
        "results": results_to_send,
    }).encode("utf-8")

    req = urllib.request.Request(
        webapp_url,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            body = response.read().decode("utf-8")
            logger.info("Sheet sync response: %s", body)
            return {"status": "sent", "response": json.loads(body)}
    except urllib.error.URLError as e:
        logger.error("Sheet sync failed: %s", e)
        return {"status": "error", "error": str(e)}


