# PLAYLIST HELPER
# ══════════════════════════════════════════════════════════════════════════════
# Adds a newly created broadcast to a YouTube playlist.
# Playlist IDs are configured per channel in the CHANNELS dict above.
# This step is non-fatal — if it fails, the broadcast is still valid.


def add_to_playlist(youtube, playlist_id: str, broadcast_id: str) -> bool:
    """
    Add a broadcast video to a YouTube playlist.

    Uses the playlistItems().insert() API call. The playlist must belong to
    the same Google account that owns the broadcast.

    Returns True on success, False on failure. Failures are non-fatal —
    the broadcast goes live normally even if playlist insertion fails.
    """
    try:
        youtube.playlistItems().insert(
            part="snippet",
            body={
                "snippet": {
                    "playlistId": playlist_id,
                    "resourceId": {
                        "kind": "youtube#video",
                        "videoId": broadcast_id,
                    },
                }
            },
        ).execute()
        logger.info("Added broadcast %s to playlist %s", broadcast_id, playlist_id)
        return True
    except HttpError as e:
        logger.warning(
            "Could not add broadcast %s to playlist %s: %s",
            broadcast_id,
            playlist_id,
            e,
        )
        return False


# ══════════════════════════════════════════════════════════════════════════════
# VIEWER REPORT — looks back at last Sunday's completed broadcasts
# ══════════════════════════════════════════════════════════════════════════════
# Fetches the peak concurrent viewer count for each channel's most recent
# completed broadcast. Results are collected across all channels and included
# in the weekly summary email.


def get_last_completed_broadcast(
    youtube, channel_id: str, last_sunday: datetime.date
) -> dict | None:
    """
    Find the most recently completed broadcast for a channel.

    Prefers a broadcast scheduled on last Sunday's date. Falls back to the
    most recent completed broadcast overall if none is found for that exact
    date — this handles edge cases like holiday schedule changes.

    Returns the full broadcast resource dict from the YouTube API, or None
    if no completed broadcasts exist for the channel.
    """
    try:
        response = (
            youtube.liveBroadcasts()
            .list(
                part="snippet,status,statistics",
                broadcastStatus="completed",
                broadcastType="all",
                maxResults=10,
            )
            .execute()
        )

        broadcasts = [
            b
            for b in response.get("items", [])
            if b["snippet"].get("channelId") == channel_id
        ]

        if not broadcasts:
            logger.warning("No completed broadcasts found for channel: %s", channel_id)
            return None

        sunday_str = last_sunday.isoformat()
        sunday_broadcasts = [
            b
            for b in broadcasts
            if b["snippet"].get("scheduledStartTime", "").startswith(sunday_str)
        ]

        pool = sunday_broadcasts if sunday_broadcasts else broadcasts
        pool.sort(
            key=lambda b: b["snippet"].get("scheduledStartTime", ""), reverse=True
        )
        return pool[0]

    except HttpError as e:
        logger.error("YouTube API error fetching broadcasts for %s: %s", channel_id, e)
        return None


def get_max_concurrent_viewers(
    youtube, youtube_analytics, broadcast_id: str, channel_id: str
) -> int | None:
    """
    Fetch the peak concurrent viewer count for a completed broadcast.

    Strategy:
      1. First tries liveStreamingDetails.concurrentViewers from the Videos API
         — fast but only available briefly (a few hours) after the stream ends.
      2. Falls back to the YouTube Analytics API peakConcurrentViewers metric,
         which stores data permanently and works days or weeks after the stream.
         This is the method that runs on Tuesday for Sunday streams.

    Returns the peak viewer count as an int, or None if unavailable from either source.
    """
    # ── Attempt 1: Videos API (works right after stream ends) ─────────────────
    try:
        response = (
            youtube.videos()
            .list(
                part="liveStreamingDetails,snippet",
                id=broadcast_id,
            )
            .execute()
        )
        items = response.get("items", [])
        if items:
            viewers = items[0].get("liveStreamingDetails", {}).get("concurrentViewers")
            if viewers is not None:
                logger.info("Viewer count from Videos API: %s", viewers)
                return int(viewers)
    except HttpError as e:
        logger.warning("Videos API failed for %s: %s", broadcast_id, e)

    # ── Attempt 2: YouTube Analytics API (reliable for streams 3+ days old) ───
    if youtube_analytics is None:
        logger.warning(
            "Analytics client not available — cannot fall back for %s", broadcast_id
        )
        return None

    try:
        # Get actual start/end times from the video resource
        video_resp = (
            youtube.videos()
            .list(
                part="snippet,liveStreamingDetails",
                id=broadcast_id,
            )
            .execute()
        )

        video_items = video_resp.get("items", [])
        if not video_items:
            return None

        snippet = video_items[0].get("snippet", {})
        live_details = video_items[0].get("liveStreamingDetails", {})

        start_time = live_details.get("actualStartTime") or snippet.get(
            "publishedAt", ""
        )
        end_time = live_details.get("actualEndTime")

        if not start_time:
            return None

        start_date = start_time[:10]
        end_date = end_time[:10] if end_time else start_date

        # Query Analytics for peak concurrent viewers.
        # NOTE: dimensions="video" is intentionally omitted — the Analytics API
        # does not support peakConcurrentViewers with a video dimension filter.
        # Without dimensions, rows[0] = [peak_viewers] (a single value).
        analytics_resp = (
            youtube_analytics.reports()
            .query(
                ids=f"channel=={channel_id}",
                startDate=start_date,
                endDate=end_date,
                metrics="peakConcurrentViewers",
                filters=f"video=={broadcast_id}",
            )
            .execute()
        )

        rows = analytics_resp.get("rows", [])
        if rows:
            peak = rows[0][0]  # Single value — no dimension column
            logger.info("Peak viewers from Analytics API: %s", peak)
            return int(peak)

        logger.warning("Analytics API returned no rows for broadcast %s", broadcast_id)
        return None

    except HttpError as e:
        logger.error("Analytics API error for %s: %s", broadcast_id, e)
        return None


def fetch_viewer_stats(
    channel_key: str, channel: dict, last_sunday: datetime.date
) -> dict:
    """
    Fetch last Sunday's peak concurrent viewer count for one channel.

    Authenticates, finds the most recent completed broadcast, and returns
    a result dict with status "success" and the viewer count, or status
    "error" with a descriptive message if any step fails.

    Errors are non-fatal — a failure on one channel does not stop the
    other channels from being processed.
    """
    label = channel["label"]
    channel_id = channel["channel_id"]

    if channel_id.startswith("YOUR_"):
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": "Channel ID not configured",
        }

    refresh_token = get_refresh_token(channel)
    if not refresh_token:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": f"Missing env var: {channel['refresh_token_env']}",
        }

    try:
        youtube, youtube_analytics = get_youtube_client(refresh_token)
    except Exception as e:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": f"Auth failed: {e}",
        }

    broadcast = get_last_completed_broadcast(youtube, channel_id, last_sunday)
    if not broadcast:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": "No completed broadcast found for last Sunday",
        }

    broadcast_id = broadcast["id"]
    broadcast_title = broadcast["snippet"].get("title", "Unknown")
    scheduled_start = broadcast["snippet"].get("scheduledStartTime", "")
    stream_date = scheduled_start[:10] if scheduled_start else "Unknown"

    max_viewers = get_max_concurrent_viewers(
        youtube, youtube_analytics, broadcast_id, channel_id
    )
    if max_viewers is None:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "broadcast_title": broadcast_title,
            "error": "Viewer count not yet available",
        }

    logger.info(
        "[%s] Max viewers: %s for '%s'", channel_key, max_viewers, broadcast_title
    )
    return {
        "status": "success",
        "channel": channel_key,
        "label": label,
        "broadcast_id": broadcast_id,
        "broadcast_title": broadcast_title,
        "stream_date": stream_date,
        "watch_url": f"https://www.youtube.com/watch?v={broadcast_id}",
        "max_concurrent_viewers": max_viewers,
    }


# ══════════════════════════════════════════════════════════════════════════════
# EVENT CREATOR — looks ahead to next Sunday's upcoming broadcasts
# ══════════════════════════════════════════════════════════════════════════════
# Creates a scheduled YouTube Live broadcast for each channel and binds it to
# that channel's existing persistent stream. Because the stream is persistent,
# the RTMP ingest key in ProPresenter never needs to change — new broadcasts
# just appear each week bound to the same key.
#
# Each broadcast is also added to the channel's playlist automatically.
# Note: live chat and comments must be disabled in YouTube Studio → Settings →
# Community → Defaults — the YouTube API does not support disabling them.


def create_live_event(
    youtube,
    channel_id: str,
    stream_id: str,
    title: str,
    start_time: datetime.datetime,
    privacy: str,
    description: str,
    enable_embed: bool = True,
) -> dict:
    """
    Create a scheduled YouTube Live broadcast and bind it to a persistent stream.

    This function performs two API calls in sequence:

      1. liveBroadcasts().insert()
             Creates the broadcast with title, description, start time, and privacy.

      2. liveBroadcasts().bind()
             Binds the broadcast to the channel's existing persistent stream
             (identified by stream_id). This keeps the RTMP key in ProPresenter
             stable week to week. No new stream is ever created by this function.

    Note: comment disabling is not handled here — YouTube's API does not reliably
    apply commentStatus to live broadcasts. Set the default in YouTube Studio →
    Settings → Community → Defaults for each channel instead.

    Returns a dict with status "created" and the broadcast details on success.
    """

    # 1. Create broadcast — chat and chat replay disabled at insert time
    broadcast = (
        youtube.liveBroadcasts()
        .insert(
            part="snippet,status,contentDetails",
            body={
                "snippet": {
                    "title": title,
                    "description": description,
                    "scheduledStartTime": start_time.isoformat(),
                    "channelId": channel_id,
                },
                "status": {
                    "privacyStatus": privacy,
                    "selfDeclaredMadeForKids": False,
                },
                "contentDetails": {
                    "enableAutoStart": False,
                    "enableAutoStop": False,
                    "enableDvr": True,
                    "enableEmbed": enable_embed,
                    "recordFromStart": True,
                    "monitorStream": {
                        "enableMonitorStream": True,
                        "broadcastStreamDelayMs": 0,
                    },
                },
            },
        )
        .execute()
    )

    broadcast_id = broadcast["id"]

    # 2. Bind broadcast to the existing persistent stream.
    #    No liveStreams().insert() — the RTMP key never changes.
    youtube.liveBroadcasts().bind(
        part="id,contentDetails",
        id=broadcast_id,
        streamId=stream_id,
    ).execute()
    logger.info(
        "[%s] Bound broadcast %s to persistent stream %s",
        channel_id,
        broadcast_id,
        stream_id,
    )

    logger.info("[%s] Created broadcast: %s → %s", channel_id, title, broadcast_id)
    return {
        "status": "created",
        "broadcast_id": broadcast_id,
        "stream_id": stream_id,
        "watch_url": f"https://www.youtube.com/watch?v={broadcast_id}",
        "title": title,
        "start_time": start_time.isoformat(),
    }


def schedule_next_event(
    channel_key: str, channel: dict, next_sunday: datetime.date, dry_run: bool = False
) -> dict:
    """
    Orchestrate the full event creation flow for one channel.

    Steps:
      1. Validate the channel ID and resolve credentials from env vars.
      2. Build the broadcast title from title_prefix + date
         e.g. "普通話主日崇拜 – May 11, 2026"
      3. Call create_live_event() to create the broadcast and bind the stream.
      4. Upload the channel's thumbnail from S3.
      5. Add the broadcast to the channel's playlist (if configured).

    Returns a result dict with status "created" on success, "dry_run" if
    dry_run=True (no YouTube writes made), or "error" with a message if
    any step fails. Errors on one channel do not affect other channels.
    """
    label = channel["label"]
    channel_id = channel["channel_id"]
    bucket = os.environ.get("EVENTS_S3_BUCKET", "")

    if channel_id.startswith("YOUR_"):
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": "Channel ID not configured — replace placeholder in CHANNELS config",
        }

    refresh_token = get_refresh_token(channel)
    if not refresh_token:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": f"Missing env var: {channel['refresh_token_env']}",
        }

    stream_id = os.environ.get(channel["stream_id_env"])
    if not stream_id:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": f"Missing env var: {channel['stream_id_env']}",
        }

    # Build title from the channel's language-specific prefix + formatted date
    # e.g. "普通話主日崇拜 – May 11, 2026" or "English Sunday Service – May 11, 2026"
    date_str = format_date(next_sunday)
    title = f"{channel['title_prefix']} – {date_str}"

    start_time = make_stream_datetime(
        next_sunday, channel["stream_hour"], channel["stream_minute"]
    )

    logger.info(
        "[%s] Scheduling: '%s' at %s",
        channel_key,
        title,
        start_time.strftime("%I:%M %p PST"),
    )

    if dry_run:
        return {
            "status": "dry_run",
            "channel": channel_key,
            "label": label,
            "title": title,
            "start_time": start_time.isoformat(),
            "thumbnail_s3_key": channel["thumbnail_s3_key"],
            "note": "Dry run — no event created on YouTube, no thumbnail uploaded",
        }

    try:
        youtube, _ = get_youtube_client(refresh_token)
    except Exception as e:
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": f"Auth failed: {e}",
        }

    try:
        result = create_live_event(
            youtube=youtube,
            channel_id=channel_id,
            stream_id=stream_id,
            title=title,
            start_time=start_time,
            privacy=channel["privacy"],
            description=channel["description"],
            enable_embed=channel.get("enable_embed", True),
        )
        result.update({"channel": channel_key, "label": label})

        # Upload thumbnail from S3
        thumbnail_ok = False
        if bucket and channel.get("thumbnail_s3_key"):
            thumbnail_ok = upload_thumbnail(
                youtube=youtube,
                broadcast_id=result["broadcast_id"],
                bucket=bucket,
                s3_key=channel["thumbnail_s3_key"],
            )
        else:
            logger.warning(
                "[%s] No thumbnail configured or EVENTS_S3_BUCKET not set", channel_key
            )

        result["thumbnail_uploaded"] = thumbnail_ok

        # Add to playlist if one is configured for this channel
        playlist_id = channel.get("playlist_id", "")
        if playlist_id:
            playlist_ok = add_to_playlist(
                youtube=youtube,
                playlist_id=playlist_id,
                broadcast_id=result["broadcast_id"],
            )
            result["playlist_added"] = playlist_ok
        else:
            result["playlist_added"] = False

        return result

    except HttpError as e:
        logger.error("[%s] YouTube API error: %s", channel_key, e)
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": str(e),
        }
    except Exception as e:
        logger.error("[%s] Unexpected error: %s", channel_key, e)
        return {
            "status": "error",
            "channel": channel_key,
            "label": label,
            "error": str(e),
        }


