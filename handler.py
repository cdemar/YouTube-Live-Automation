# DATE HELPERS
# ══════════════════════════════════════════════════════════════════════════════
# Utility functions for calculating the two target Sundays and formatting dates.
# No configuration needed here.


def get_last_sunday() -> datetime.date:
    """Return the date of the most recent Sunday (always in the past)."""
    today = datetime.date.today()
    days_since_sunday = (today.weekday() + 1) % 7
    return today - datetime.timedelta(
        days=days_since_sunday if days_since_sunday > 0 else 7
    )


def get_next_sunday() -> datetime.date:
    """Return the date of the coming Sunday (always in the future)."""
    today = datetime.date.today()
    days_until_sunday = (6 - today.weekday()) % 7
    return today + datetime.timedelta(
        days=days_until_sunday if days_until_sunday > 0 else 7
    )


def make_stream_datetime(
    date: datetime.date, hour: int, minute: int
) -> datetime.datetime:
    """Build a timezone-aware PST/PDT datetime for a given date and time."""
    return datetime.datetime(date.year, date.month, date.day, hour, minute, tzinfo=PST)


def format_date(date: datetime.date) -> str:
    """Format a date as 'May 11, 2026'."""
    return date.strftime("%B %-d, %Y")


