# THUMBNAIL HELPER
# ══════════════════════════════════════════════════════════════════════════════
# Downloads a thumbnail image from S3 and uploads it to a YouTube broadcast.
# Thumbnails are stored in S3 once and reused automatically every week —
# no manual uploads or file management required after initial setup.


def upload_thumbnail(youtube, broadcast_id: str, bucket: str, s3_key: str) -> bool:
    """
    Download a thumbnail image from S3 and set it on a YouTube broadcast.

    The image is read into memory and streamed directly to the YouTube
    Thumbnails API — it is never written to disk.

    Returns True on success, False on any failure. Failures are non-fatal:
    the broadcast is still valid and will go live even without a thumbnail.

    YouTube thumbnail requirements:
        Format:      JPG or PNG
        Max size:    2 MB
        Recommended: 1280x720 px (16:9 aspect ratio)
    """
    try:
        obj = s3.get_object(Bucket=bucket, Key=s3_key)
        image_data = obj["Body"].read()
        content_type = obj.get("ContentType", "image/jpeg")

        logger.info(
            "Uploading thumbnail from s3://%s/%s (%d bytes)",
            bucket,
            s3_key,
            len(image_data),
        )

        from googleapiclient.http import MediaInMemoryUpload

        media = MediaInMemoryUpload(image_data, mimetype=content_type, resumable=False)

        youtube.thumbnails().set(
            videoId=broadcast_id,
            media_body=media,
        ).execute()

        logger.info("Thumbnail uploaded for broadcast: %s", broadcast_id)
        return True

    except s3.exceptions.NoSuchKey:
        logger.error("Thumbnail not found in S3: s3://%s/%s", bucket, s3_key)
        logger.error("Please upload your thumbnail to S3 before running.")
        return False
    except HttpError as e:
        logger.error("YouTube thumbnail upload failed for %s: %s", broadcast_id, e)
        return False
    except Exception as e:
        logger.error("Unexpected thumbnail error for %s: %s", broadcast_id, e)
        return False


